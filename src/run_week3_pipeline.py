def generate_live_ragas_smoke(out_dir: Path) -> None:
    """Generate the 5-row live RAGAS score files used by the dashboard."""
    old_env = {
        key: os.environ.get(key)
        for key in (
            "GRAPH_PREDICTIONS_CSV",
            "GRAPH_RAGAS_SCORES_JSON",
            "GRAPH_RAGAS_ROWS_CSV",
            "RAGAS_MAX_WORKERS",
            "RAGAS_TIMEOUT_SEC",
            "GROQ_MAX_RETRIES",
        )
    }
    smoke_csv = out_dir / "ragas_smoke_graphrag_5.csv"
    if not smoke_csv.exists():
        raise FileNotFoundError(
            f"Missing RAGAS smoke predictions CSV: {smoke_csv}. "
            "Run create_ragas_smoke_subset() before live RAGAS evaluation."
        )
    os.environ.update(
        {
            "GRAPH_PREDICTIONS_CSV": str(out_dir / "ragas_smoke_graphrag_5.csv"),
            "GRAPH_RAGAS_SCORES_JSON": str(out_dir / "ragas_smoke_graphrag_5_scores.json"),
            "GRAPH_RAGAS_ROWS_CSV": str(out_dir / "ragas_smoke_graphrag_5_rows.csv"),
            "RAGAS_MAX_WORKERS": os.environ.get("RAGAS_MAX_WORKERS", "1"),
            "RAGAS_TIMEOUT_SEC": os.environ.get("RAGAS_TIMEOUT_SEC", "900"),
            "GROQ_MAX_RETRIES": os.environ.get("GROQ_MAX_RETRIES", "8"),
        }
    )
    try:
        _run_module("src.week2_graph_rag.run_eval_week2")
    finally:
        for key, value in old_env.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


