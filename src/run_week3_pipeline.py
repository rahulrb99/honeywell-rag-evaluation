"""Week 3 end-to-end benchmark pipeline.

Default flow:
    raw Honeywell docs -> GraphRAG predictions -> vector RAG predictions ->
    Week 3 metrics/RAGAS/judge artifacts -> static dashboard.

Usage:
    python -m src.run_week3_pipeline
    python -m src.run_week3_pipeline --skip-live-ragas --skip-llm-judge
    python -m src.run_week3_pipeline --skip-graph-domain-build
"""

from __future__ import annotations

import argparse
import json
import os
import runpy
import sys
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "outputs" / "eval_outputs"
PREDICTIONS_DIR = ROOT / "outputs" / "predictions"
REPORT = OUT_DIR / "benchmarking_comparative_analysis.md"

DASHBOARD_INPUTS = [
    OUT_DIR / "eval_results.csv",
    OUT_DIR / "summary_by_query_class.csv",
    OUT_DIR / "failure_analysis.csv",
    OUT_DIR / "metric_summary.json",
]

DASHBOARD = OUT_DIR / "dashboard.html"


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run the end-to-end Week 3 GraphRAG/vector/RAGAS/judge dashboard pipeline."
    )
    parser.add_argument(
        "--dataset",
        default=str(ROOT / "data" / "eval" / "honeywell_hard_labels_28.csv"),
        help="Benchmark/gold dataset CSV.",
    )
    parser.add_argument(
        "--graph-output",
        default=str(PREDICTIONS_DIR / "honeywell_hard_labels_28_graphrag.csv"),
        help=(
            "GraphRAG output CSV with id, answer, retrieved_contexts. If missing, "
            "the pipeline generates it with src.week2_graph_rag.run_graphrag_predictions."
        ),
    )
    parser.add_argument(
        "--vector-output",
        default=str(PREDICTIONS_DIR / "vector_rag_hard_labels_28_predictions.csv"),
        help=(
            "Vector/baseline RAG output CSV with id, answer, retrieved_contexts. "
            "If missing, the Week 3 evaluator generates it with the vector RAG baseline."
        ),
    )
    parser.add_argument(
        "--generate-vector-output",
        action="store_true",
        help=(
            "Backward-compatible no-op. Vector predictions are generated by default "
            "when the output CSV is missing."
        ),
    )
    parser.add_argument(
        "--skip-graph-domain-build",
        action="store_true",
        help="Do not build/update the Neo4j GraphRAG domain before generating GraphRAG predictions.",
    )
    parser.add_argument(
        "--skip-graph-output-generation",
        action="store_true",
        help="Require --graph-output to already exist instead of generating it.",
    )
    parser.add_argument(
        "--skip-vector-output-generation",
        action="store_true",
        help="Require --vector-output to already exist instead of generating it.",
    )
    parser.add_argument(
        "--force-regenerate-outputs",
        action="store_true",
        help="Regenerate GraphRAG and vector RAG prediction CSVs even when they already exist.",
    )
    parser.add_argument(
        "--manual-review",
        default="",
        help="Optional manual review CSV for kappa analysis.",
    )
    parser.add_argument(
        "--llm-judge",
        default="",
        help="Optional existing LLM-judge CSV for kappa analysis.",
    )
    parser.add_argument(
        "--run-llm-judge",
        action="store_true",
        help="Backward-compatible no-op. Pairwise LLM-as-a-judge runs by default.",
    )
    parser.add_argument(
        "--skip-llm-judge",
        action="store_true",
        help="Skip pairwise LLM-as-a-judge generation for a faster local debug run.",
    )
    parser.add_argument(
        "--ragas-scores",
        default="",
        help="Optional existing RAGAS smoke scores JSON to include in the dashboard.",
    )
    parser.add_argument(
        "--out-dir",
        default=str(OUT_DIR),
        help="Directory for generated CSV/JSON/HTML dashboard artifacts.",
    )
    parser.add_argument(
        "--report",
        default=str(REPORT),
        help="Markdown report path generated by the evaluator.",
    )
    parser.add_argument(
        "--live-ragas",
        action="store_true",
        help="Backward-compatible no-op. Live 5-row RAGAS smoke scoring runs by default.",
    )
    parser.add_argument(
        "--skip-live-ragas",
        action="store_true",
        help="Skip the live 5-row RAGAS smoke score generation.",
    )
    return parser.parse_args()


def _relative(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def _check_files(paths: list[Path], label: str) -> None:
    missing = [path for path in paths if not path.exists()]
    if missing:
        missing_list = "\n".join(f"  - {_relative(path)}" for path in missing)
        raise FileNotFoundError(
            f"Missing required {label}:\n"
            f"{missing_list}\n\n"
            "Use --graph-output/--vector-output to point at supplied CSVs, or "
            "leave generation enabled so the pipeline builds missing outputs."
        )


def _optional_path(raw: str) -> Path | None:
    return Path(raw) if raw else None


def _run_module(module: str, args: list[str] | None = None) -> None:
    old_argv = sys.argv[:]
    sys.argv = [module, *(args or [])]
    try:
        print(f"\nRunning: python -m {module} {' '.join(args or [])}".rstrip())
        runpy.run_module(module, run_name="__main__")
    finally:
        sys.argv = old_argv


def _with_env(updates: dict[str, str]):
    old_env = {key: os.environ.get(key) for key in updates}
    os.environ.update(updates)
    return old_env


def _restore_env(old_env: dict[str, str | None]) -> None:
    for key, value in old_env.items():
        if value is None:
            os.environ.pop(key, None)
        else:
            os.environ[key] = value


def generate_graph_output(args: argparse.Namespace) -> None:
    """Build the GraphRAG domain when requested and write GraphRAG predictions."""
    graph_output = Path(args.graph_output)
    if graph_output.exists() and not args.force_regenerate_outputs:
        print(f"\nGraphRAG predictions already exist: {_relative(graph_output)}")
        return
    if args.skip_graph_output_generation:
        raise FileNotFoundError(f"Missing GraphRAG predictions CSV: {graph_output}")

    if not args.skip_graph_domain_build:
        _run_module("src.week2_graph_rag.build_honeywell_graphrag_domain")
    else:
        print("\nSkipping GraphRAG domain build; using existing Neo4j domain.")

    old_env = _with_env(
        {
            "GRAPH_EVAL_CSV": args.dataset,
            "GRAPH_PREDICTIONS_CSV": str(graph_output),
        }
    )
    try:
        _run_module("src.week2_graph_rag.run_graphrag_predictions")
    finally:
        _restore_env(old_env)


def ensure_vectorstore() -> None:
    """Build the FAISS vectorstore if it is not already present."""
    index_path = ROOT / "data" / "vectorstore" / "index.faiss"
    if index_path.exists():
        print(f"\nVectorstore already exists: {_relative(index_path)}")
        return
    _run_module("src.ingest")


def generate_week3_metrics(args: argparse.Namespace) -> None:
    """Generate the row results, query-class summary, failure CSV, and metric JSON."""
    module_args = [
        "--benchmark",
        args.dataset,
        "--graph-predictions",
        args.graph_output,
        "--vector-predictions",
        args.vector_output,
        "--manual-review",
        args.manual_review or str(ROOT / "missing_manual_review.csv"),
        "--out-dir",
        args.out_dir,
        "--report",
        args.report,
    ]
    if args.skip_vector_output_generation:
        module_args.append("--no-generate-vector")
    _run_module("src.week3_benchmark.run_week3_eval", module_args)


def generate_live_ragas_smoke(out_dir: Path) -> None:
    """Generate the 5-row live RAGAS score files used by the dashboard."""
    old_env = {
        key: os.environ.get(key)
        for key in (
            "GRAPH_PREDICTIONS_CSV",
            "GRAPH_RAGAS_SCORES_JSON",
            "GRAPH_RAGAS_ROWS_CSV",
            "RAGAS_MAX_WORKERS",
            "RAGAS_TIMEOUT_SEC",
            "GROQ_MAX_RETRIES",
        )
    }
    smoke_csv = out_dir / "ragas_smoke_graphrag_5.csv"
    if not smoke_csv.exists():
        raise FileNotFoundError(
            f"Missing RAGAS smoke predictions CSV: {smoke_csv}. "
            "Run create_ragas_smoke_subset() before live RAGAS evaluation."
        )
    os.environ.update(
        {
            "GRAPH_PREDICTIONS_CSV": str(out_dir / "ragas_smoke_graphrag_5.csv"),
            "GRAPH_RAGAS_SCORES_JSON": str(out_dir / "ragas_smoke_graphrag_5_scores.json"),
            "GRAPH_RAGAS_ROWS_CSV": str(out_dir / "ragas_smoke_graphrag_5_rows.csv"),
            "RAGAS_MAX_WORKERS": os.environ.get("RAGAS_MAX_WORKERS", "1"),
            "RAGAS_TIMEOUT_SEC": os.environ.get("RAGAS_TIMEOUT_SEC", "900"),
            "GROQ_MAX_RETRIES": os.environ.get("GROQ_MAX_RETRIES", "8"),
        }
    )
    try:
        _run_module("src.week2_graph_rag.run_eval_week2")
    finally:
        for key, value in old_env.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def generate_kappa_analysis(args: argparse.Namespace, out_dir: Path) -> bool:
    """Generate the Cohen's Kappa rows and summary used by the dashboard."""
    manual_review = _optional_path(args.manual_review)
    llm_judge = _optional_path(args.llm_judge)
    if not manual_review or not llm_judge:
        print("\nSkipping kappa analysis; --manual-review and --llm-judge were not both provided.")
        return False

    _run_module(
        "src.week3_benchmark.run_kappa_analysis",
        [
            "--manual-review",
            str(manual_review),
            "--llm-judge",
            str(llm_judge),
            "--week3-results",
            str(out_dir / "eval_results.csv"),
            "--output-csv",
            str(out_dir / "kappa_analysis.csv"),
            "--output-json",
            str(out_dir / "kappa_summary.json"),
        ],
    )
    return True


def generate_pairwise_llm_judge(out_dir: Path) -> Path:
    output_json = out_dir / "pairwise_llm_judge_summary.json"
    _run_module(
        "src.week3_benchmark.run_pairwise_llm_judge",
        [
            "--results",
            str(out_dir / "eval_results.csv"),
            "--output-csv",
            str(out_dir / "pairwise_llm_judge.csv"),
            "--output-json",
            str(output_json),
        ],
    )
    return output_json


def create_ragas_smoke_subset(graph_output: str, out_dir: Path) -> Path:
    """Create a 5-row GraphRAG subset for live RAGAS smoke validation."""
    graph_df = pd.read_csv(graph_output)
    if graph_df.empty:
        raise ValueError("GraphRAG output CSV is empty; cannot create RAGAS smoke subset")
    if "query_class" in graph_df.columns:
        hard_classes = {"multi_hop", "theme_summary", "relationship_reasoning", "comparison"}
        subset = graph_df[graph_df["query_class"].isin(hard_classes)].head(5)
        if len(subset) < 5:
            subset = graph_df.head(5)
    else:
        subset = graph_df.head(5)
    out_path = out_dir / "ragas_smoke_graphrag_5.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    subset.to_csv(out_path, index=False)
    print(f"Saved RAGAS smoke subset -> {out_path}")
    return out_path


def build_dashboard(
    args: argparse.Namespace,
    out_dir: Path,
    kappa_generated: bool,
    llm_judge_summary: Path | None,
) -> None:
    """Build the static Week 3 dashboard HTML."""
    module_args = [
        "--results",
        str(out_dir / "eval_results.csv"),
        "--summary",
        str(out_dir / "summary_by_query_class.csv"),
        "--metrics",
        str(out_dir / "metric_summary.json"),
        "--output",
        str(out_dir / "dashboard.html"),
    ]
    if kappa_generated:
        module_args.extend(["--kappa", str(out_dir / "kappa_summary.json")])
    else:
        module_args.extend(["--kappa", str(out_dir / "_missing_kappa_summary.json")])
    if args.ragas_scores:
        module_args.extend(["--ragas", args.ragas_scores])
    elif not args.skip_live_ragas:
        module_args.extend(["--ragas", str(out_dir / "ragas_smoke_graphrag_5_scores.json")])
    else:
        module_args.extend(["--ragas", str(out_dir / "_missing_ragas_scores.json")])
    if llm_judge_summary:
        module_args.extend(["--llm-judge-summary", str(llm_judge_summary)])
    else:
        module_args.extend(["--llm-judge-summary", str(out_dir / "_missing_llm_judge_summary.json")])
    _run_module("src.week3_benchmark.build_week3_dashboard", module_args)


def _print_metric_snapshot(out_dir: Path) -> None:
    metrics_path = out_dir / "metric_summary.json"
    metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
    winner_counts = metrics.get("winner_counts", {})
    print("\nMetric snapshot")
    print(f"  Rows evaluated: {metrics.get('rows')}")
    print(f"  GraphRAG wins: {winner_counts.get('graph', 0)}")
    print(f"  Vector wins:   {winner_counts.get('vector', 0)}")
    print(f"  Ties:          {winner_counts.get('tie', 0)}")
    print(f"  Neither:       {winner_counts.get('neither', 0)}")
    print(f"  Hard-query GraphRAG win rate: {metrics.get('hard_query_graph_win_rate')}")


def main() -> None:
    args = _parse_args()
    out_dir = Path(args.out_dir)
    dashboard = out_dir / "dashboard.html"
    print("GraphEval-Ragas Week 3 pipeline")
    print("Generating GraphRAG, vector RAG, evaluation artifacts, and dashboard.\n")

    required_inputs = [Path(args.dataset)]
    if args.skip_graph_output_generation:
        required_inputs.append(Path(args.graph_output))
    if args.skip_vector_output_generation:
        required_inputs.append(Path(args.vector_output))
    if args.ragas_scores:
        required_inputs.append(Path(args.ragas_scores))
    _check_files(required_inputs, "source inputs")
    print("Required source inputs: OK")

    generate_graph_output(args)
    vector_output = Path(args.vector_output)
    vector_output_needed = args.force_regenerate_outputs or not vector_output.exists()
    if not args.skip_vector_output_generation and vector_output_needed:
        ensure_vectorstore()
    generate_week3_metrics(args)
    if args.ragas_scores:
        print(f"\nUsing supplied RAGAS scores: {_relative(Path(args.ragas_scores))}")
    elif not args.skip_live_ragas:
        create_ragas_smoke_subset(args.graph_output, out_dir)
        generate_live_ragas_smoke(out_dir)
    else:
        print("\nSkipping live RAGAS smoke regeneration.")
        print("Use --ragas-scores to include existing smoke scores.")

    kappa_generated = generate_kappa_analysis(args, out_dir)
    llm_judge_summary = None if args.skip_llm_judge else generate_pairwise_llm_judge(out_dir)
    _check_files([out_dir / path.name for path in DASHBOARD_INPUTS], "dashboard inputs")
    build_dashboard(args, out_dir, kappa_generated, llm_judge_summary)
    _print_metric_snapshot(out_dir)

    print("\nOpen/read these files:")
    print(f"  Dashboard: {_relative(dashboard)}")
    print(f"  Report:    {_relative(Path(args.report))}")
    print("\nWeek 3 pipeline complete.")


if __name__ == "__main__":
    main()
