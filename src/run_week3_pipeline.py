def create_ragas_smoke_subset(graph_output: str, out_dir: Path) -> Path:
    """Create a 5-row GraphRAG subset for live RAGAS smoke validation."""
    graph_df = pd.read_csv(graph_output)
    if graph_df.empty:
        raise ValueError("GraphRAG output CSV is empty; cannot create RAGAS smoke subset")
    if "query_class" in graph_df.columns:
        hard_classes = {"multi_hop", "theme_summary", "relationship_reasoning", "comparison"}
        subset = graph_df[graph_df["query_class"].isin(hard_classes)].head(5)
        if len(subset) < 5:
            subset = graph_df.head(5)
    else:
        subset = graph_df.head(5)
    out_path = out_dir / "ragas_smoke_graphrag_5.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    subset.to_csv(out_path, index=False)
    print(f"Saved RAGAS smoke subset -> {out_path}")
    return out_path


